-- A GitHub home: an organisation GitHub repos are filed under. Its published
-- systems are those under it or in one of its GitHub accounts, live now
-- (BR-1.13) — a client system counts towards the home it was built in only
-- when the client may be named (BR-1.4).
CREATE VIEW "PublicHome" AS
 SELECT o."id", o."name", o."slug", o."role", k."key" AS "kind", o."githubLogins",
        (SELECT count(*)::int
           FROM "System" s
           LEFT JOIN "Organization" so ON so."id" = s."organizationId"
          WHERE is_live(s."contentStatus", s."publishAt")
            AND (s."clientVisibility" = 'PUBLIC' OR s."clientApproved")
            AND (s."clientVisibility" <> 'ANONYMIZED_ONLY' OR s."nameDisclosureApproved" OR s."organizationId" = o."id")
            AND (s."organizationId" = o."id"
                 OR lower(s."githubOwnerLogin") = ANY (SELECT lower(l) FROM unnest(o."githubLogins") l))
        ) AS "publishedSystems"
   FROM "Organization" o
   LEFT JOIN "OrganizationKind" k ON k."id" = o."kindId"
  WHERE cardinality(o."githubLogins") > 0;

-- ---------------------------------------------------------------- pulse
-- Business rules the database itself enforces: every distinct BR-x.y named in
-- a constraint, a trigger, or the body of one of our functions.
CREATE VIEW "PublicPlatformPulse" AS
 WITH sources AS (
   SELECT c."conname"::text || ' ' || pg_get_constraintdef(c."oid") AS src
     FROM pg_constraint c JOIN pg_namespace n ON n."oid" = c."connamespace"
    WHERE n."nspname" = 'public'
   UNION ALL
   SELECT t."tgname"::text
     FROM pg_trigger t JOIN pg_class r ON r."oid" = t."tgrelid" JOIN pg_namespace n ON n."oid" = r."relnamespace"
    WHERE n."nspname" = 'public' AND NOT t."tgisinternal"
   UNION ALL
   SELECT p."prosrc"
     FROM pg_proc p JOIN pg_namespace n ON n."oid" = p."pronamespace"
    WHERE n."nspname" = 'public' AND p."prolang" = (SELECT "oid" FROM pg_language WHERE "lanname" = 'plpgsql')
 ), rules AS (
   SELECT DISTINCT m[1] || '.' || m[2] AS rule
     FROM sources, regexp_matches(src, 'BR[-_]([0-9]+)[._]([0-9]+)', 'gi') AS m
 )
 SELECT 1 AS "id",
        (SELECT count(*)::int FROM rules) AS "rulesEnforcedByDatabase",
        (SELECT count(*)::int FROM "ActivityLog" WHERE "createdAt" > now() - interval '7 days') AS "auditEventsLast7Days",
        (SELECT count(*)::int FROM "ActivityLog") AS "auditEventsTotal",
        (SELECT max("finishedAt") FROM "JobRun" WHERE "status" = 'SUCCEEDED') AS "lastSuccessfulJobAt",
        (SELECT max("githubSyncedAt") FROM "System") AS "lastGithubSyncAt";

