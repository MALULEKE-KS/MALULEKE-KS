-- F5c (docs/PUBLIC-REDESIGN-PLAN.md §6) — the data the redesigned public site
-- needs. Additive only.
--
-- 1. Titles and qualifications (D13). The owner is more than one title at a
--    time — "Software & AI Engineer" and "Final-year BSc Computer Science &
--    Mathematics student" — and the set changes (graduate, Honours, a new
--    role). A ProfileTitle row per title, its kind a lookup (EXT-1), dated so a
--    finished one leaves the public view on its own while staying on record.
-- 2. The three GitHub homes (D12). OrganizationKind (personal / venture /
--    client — a lookup) tells the owner's own account and ventures from
--    clients without code. PublicHome lists the organisations GitHub repos
--    live under, with how many published systems each holds — counted in the
--    database, never exposing a draft or a masked client.
-- 3. PublicPlatformPulse (§3.2, the "control room") — the platform reporting on
--    itself: audit events, business rules the database enforces, the last
--    successful job and GitHub sync. Aggregates only: no rows, no actors.

-- ---------------------------------------------------------------- titles
CREATE TABLE "TitleKind" (
  "id"        text PRIMARY KEY,
  "key"       text NOT NULL UNIQUE,
  "label"     text NOT NULL,
  "active"    boolean NOT NULL DEFAULT true,
  "createdAt" timestamptz(3) NOT NULL DEFAULT now(),
  "updatedAt" timestamptz(3) NOT NULL DEFAULT now()
);

CREATE TABLE "ProfileTitle" (
  "id"          text PRIMARY KEY,
  "profileId"   integer NOT NULL DEFAULT 1 REFERENCES "Profile"("id") ON DELETE CASCADE ON UPDATE CASCADE,
  "kindId"      text NOT NULL REFERENCES "TitleKind"("id") ON DELETE RESTRICT ON UPDATE CASCADE,
  "label"       text NOT NULL,
  -- Where it's held, e.g. the institution of a qualification.
  "detail"      text,
  -- The education entry behind a qualification, when there is one.
  "educationId" text REFERENCES "Education"("id") ON DELETE SET NULL ON UPDATE CASCADE,
  "sortOrder"   integer NOT NULL DEFAULT 0,
  "startsOn"    date,
  "endsOn"      date,
  "createdAt"   timestamptz(3) NOT NULL DEFAULT now(),
  "updatedAt"   timestamptz(3) NOT NULL DEFAULT now(),
  CONSTRAINT "ProfileTitle_label_present" CHECK (length(btrim("label")) BETWEEN 1 AND 120),
  CONSTRAINT "ProfileTitle_detail_length" CHECK ("detail" IS NULL OR length(btrim("detail")) BETWEEN 1 AND 160),
  CONSTRAINT "ProfileTitle_dates_ordered" CHECK ("startsOn" IS NULL OR "endsOn" IS NULL OR "endsOn" >= "startsOn")
);
CREATE INDEX "ProfileTitle_profileId_sortOrder_idx" ON "ProfileTitle" ("profileId", "sortOrder");

-- Current titles only: started (or undated) and not yet ended, of an active kind.
CREATE VIEW "PublicProfileTitle" AS
 SELECT t."id", k."key" AS "kind", k."label" AS "kindLabel", t."label", t."detail", t."sortOrder", t."startsOn"
   FROM "ProfileTitle" t
   JOIN "TitleKind" k ON k."id" = t."kindId"
  WHERE k."active"
    AND (t."startsOn" IS NULL OR t."startsOn" <= current_date)
    AND (t."endsOn" IS NULL OR t."endsOn" >= current_date);

-- ---------------------------------------------------------------- homes
CREATE TABLE "OrganizationKind" (
  "id"        text PRIMARY KEY,
  "key"       text NOT NULL UNIQUE,
  "label"     text NOT NULL,
  "active"    boolean NOT NULL DEFAULT true,
  "createdAt" timestamptz(3) NOT NULL DEFAULT now(),
  "updatedAt" timestamptz(3) NOT NULL DEFAULT now()
);

ALTER TABLE "Organization" ADD COLUMN "kindId" text REFERENCES "OrganizationKind"("id") ON DELETE RESTRICT ON UPDATE CASCADE;
CREATE INDEX "Organization_kindId_idx" ON "Organization" ("kindId");

